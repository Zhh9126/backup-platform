  var lang = localStorage.getItem("aidbm_lang") || "zh";
  var CJK_RE = /[\u4e00-\u9fff]/;
  var SKIP_TAGS = { SCRIPT: 1, STYLE: 1, CODE: 1, PRE: 1, TEXTAREA: 1, NOSCRIPT: 1, TEMPLATE: 1 };
  var observer = null;

  function lookup(s) {
    if (EN.hasOwnProperty(s)) return EN[s];
    // 星号归一：表单必填标签「业务系统 *」→ 查「业务系统」
    var star = s.match(/^(.*?)\s*\*+$/);
    if (star && star[1] !== s) {
      var base = star[1].trim();
      if (EN.hasOwnProperty(base)) return EN[base] + " *";
      var b2 = lookup(base);
      if (b2 !== null && b2 !== base) return b2 + " *";
    }
    // 「 · 」组合标签分段翻译（如「体检 · 调度触发」），任一段不可译则放弃
    if (s.indexOf(" · ") > 0) {
      var parts = s.split(" · "), out = [], all = true;
      for (var pi = 0; pi < parts.length; pi++) {
        var pt = parts[pi].trim();
        var tr = EN.hasOwnProperty(pt) ? EN[pt] : null;
        if (tr === null) { all = false; break; }
        out.push(tr);
      }
      if (all && out.length > 1) return out.join(" · ");
    }
    for (var i = 0; i < PATTERNS.length; i++) {
      var m = s.match(PATTERNS[i][0]);
      if (m) return PATTERNS[i][1].replace(/\$(\d)/g, function (_, d) {
        return m[d] !== undefined ? m[d] : "";
      });
    }
    for (var j = 0; j < PREFIXES.length; j++) {
      if (s.indexOf(PREFIXES[j]) === 0) {
        var rest = s.slice(PREFIXES[j].length);
        var p = EN[PREFIXES[j]];
        return (p !== undefined ? p : PREFIXES[j]) + rest;
      }
    }
    return null;
  }

  function t(s) {
    if (s === null || s === undefined) return s;
    s = String(s);
    if (lang === "zh") return s;
    var r = lookup(s);
    return r !== null ? r : s;
  }

  function replaceFirst(txt, from, to) {
    var idx = txt.indexOf(from);
    if (idx < 0) return txt;
    return txt.slice(0, idx) + to + txt.slice(idx + from.length);
  }

  function translateTextNode(node) {
    if (!node || node.nodeType !== 3) return;
    var txt = node.nodeValue;
    if (!txt) return;
    var s = txt.trim();
    if (!s || !CJK_RE.test(s)) return;
    var p = node.parentNode;
    if (!p || SKIP_TAGS[p.nodeName]) return;
    if (p.closest && p.closest(".no-i18n")) return;
    var en = lookup(s);
    if (en === null || en === s) return;
    node.nodeValue = replaceFirst(txt, s, en);
  }

  function translateElementAttrs(el) {
    if (el.nodeType !== 1) return;
    if (el.closest && el.closest(".no-i18n")) return;
    var tag = el.nodeName;
    if (tag === "INPUT" || tag === "TEXTAREA") {
      var ph = el.getAttribute("placeholder");
      if (ph && CJK_RE.test(ph)) {
        var r = lookup(ph.trim());
        if (r !== null && r !== ph.trim()) el.setAttribute("placeholder", r);
      }
    }
    var ti = el.getAttribute && el.getAttribute("title");
    if (ti && CJK_RE.test(ti)) {
      var r2 = lookup(ti.trim());
      if (r2 !== null && r2 !== ti.trim()) el.setAttribute("title", r2);
    }
  }

  function walk(root) {
    if (lang !== "en") return;
    root = root || document.body;
    if (!root) return;
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentNode;
        if (!p || SKIP_TAGS[p.nodeName]) return NodeFilter.FILTER_REJECT;
        if (p.closest && p.closest(".no-i18n")) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var n;
    while ((n = walker.nextNode())) translateTextNode(n);
    // 属性：placeholder / title
    var els = root.querySelectorAll ? root.querySelectorAll("input[placeholder],textarea[placeholder],[title]") : [];
    for (var i = 0; i < els.length; i++) translateElementAttrs(els[i]);
  }

  function apply(root) {
    root = root || document;
    if (lang !== "en") return;
    root.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    root.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    root.querySelectorAll(".nav-label").forEach(function (el) {
      var zh = (el.textContent || "").trim();
      if (EN[zh]) el.textContent = EN[zh];
    });
    walk(root.documentElement || root);
  }

  function observeDynamic() {
    if (observer || !window.MutationObserver || lang !== "en") return;
    var queue = [], timer = null;
    var flush = function () {
      timer = null;
      var batch = queue; queue = [];
      for (var i = 0; i < batch.length; i++) {
        var m = batch[i];
        for (var j = 0; j < m.addedNodes.length; j++) {
          var nd = m.addedNodes[j];
          if (nd.nodeType === 3) translateTextNode(nd);
          else if (nd.nodeType === 1) {
            walk(nd);
            translateElementAttrs(nd);
          }
        }
        if (m.type === "attributes" && m.target) translateElementAttrs(m.target);
      }
    };
    observer = new MutationObserver(function (muts) {
      for (var k = 0; k < muts.length; k++) queue.push(muts[k]);
      if (!timer) timer = setTimeout(flush, 60);
    });
    observer.observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ["placeholder", "title"] });
  }

  function setLang(l) {
    lang = l;
    localStorage.setItem("aidbm_lang", l);
    location.reload();
  }

